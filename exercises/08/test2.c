#include <stdio.h>   // подключаем printf

// Функция принимает указатель на int (адрес переменной)
// и кладёт по этому адресу новое значение 99
void set_to_99(int *p) {
    *p = 99;         // *p — "значение по адресу p"; записываем туда 99
}

int main(void) {
    int a = 5;       // обычная переменная, значение 5

    printf("a = %d\n", a);          // печатаем: a = 5

    // &a — адрес переменной a. Передаём его в функцию.
    set_to_99(&a);

    printf("a = %d\n", a);          // печатаем: a = 99  ← значение изменилось!

    // Отдельно посмотрим на сам указатель
    int *p = &a;     // p — указатель на int, хранит адрес a
    printf("a = %d\n", *p);         // *p — достаём значение по адресу: 99

    return 0;
}

